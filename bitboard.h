struct Bitboard {
    static constexpr int W = 8;
    static constexpr int H = W;
    static constexpr int S = W*H;
    static constexpr int B = Board::SIZE;

    inline static array <u8,B> MAILBOX_TO_64 = {};
    inline static array <u64,B> BITMASK = {};
    inline static array <array <u64,B>,B> ROOK_MASKS = {};
    
    static u64 hrz_mask( off_t a, off_t b ); // a > b
    static u64 vrt_mask( off_t a, off_t b ); //
    static void initialize();

    u64 bitboard = 0;

    void insert( pos_t p ){
        bitboard |= BITMASK[p];
    }
    void erase( pos_t p ){
        bitboard ^= BITMASK[p];
    }
};
