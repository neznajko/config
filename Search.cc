constexpr int MOVSCAP = 32;
////////////////////////////////////////////////////////////////
u64 Search::perft( int depth ){
    if( depth == 0 ){ return 1; }
    vector <Move> movs; movs.reserve( MOVSCAP );
    node->get_army_moves( movs );
    u64 n = 0;
    for( const auto mov: movs ){
        node->move_fwd( mov );
        if( !node->check()){
            n += perft( depth - 1 );
        }
        node->move_bwd( mov );
    }
    return n;
}
