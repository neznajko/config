constexpr u64 U64MAX = std::numeric_limits<u64>::max();
////////////////////////////////////////////////////////////////
std::random_device                                    Hash::dev;
std::mt19937_64                                       Hash::gen;
std::uniform_int_distribution<u64>      Hash::dist( 0, U64MAX );
array<array<array<u64,Board::SIZE>,VOID>,RED>         Hash::_sq;
u64                                           Hash::_the_switch;    
////////////////////////////////////////////////////////////////
void Hash::initialize( u64 seed ){
    gen.seed( seed );
    for( fig_t f = KING; f < VOID; ++f ){
        for( pos_t p = 0; p < Board::SIZE; ++p ){
            _sq[BLACK][f][p] = genu64();
            _sq[WHITE][f][p] = genu64();
        }
    }
    _the_switch = genu64();
}
