u64 Search::perft( u8 depth ){ // depth > 0
  Picker picker;
  picker.generate( &node );
  if( depth == 1 ){
    return picker.size();
  }
  u64 n = 0;
  while( picker.has_next( )){
    const auto mov = picker.next();
    node.movfwd( mov );
    n += perft( depth - 1 );
    node.movbwd( mov );
  }
  return n;
}
