struct Tscheck { //                              thaTS
        i32 cntr; // double discovered checkmate
      off_t checking_piece_offset;
   Bitboard pinned; 
   Bitboard pinners;

  void reset() {
                     cntr = 0;
    checking_piece_offset = -1;
    
    pinned.clear();
    pinners.clear();
  }
};
