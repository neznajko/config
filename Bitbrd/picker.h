namespace config {
//////////////////////////////////////////////////////
struct Picker { //
  
  static constexpr int STKCAP = 64;

  array<Move,STKCAP> stk; // 128 B

  int T = 0;
  int j = 0;

  const Node* node;

  bool has_next() const {
    return ( j < T );
  }
  Move next() {
    return stk[ j++ ];
  }
  void push( Move mov ){
    stk[ T++ ] = mov;
  }
  void push( off_t src, off_t dst, Move::type_t type ){
    push({ Move::pack( src, dst, type )});
  }
  void clear() {
    j = T = 0;
  }
  void generate( const Node* node ){
    this->node = node;
    clear();
    genki();
  }
  int size() const {
    return T;
  }
  void genki();
};
//////////////////////////////////////////////////////
}
