# define OVERLOAD_OSTREAM_OPERATOR( Container )                \
template <typename... T>                                       \
ostream& operator<<( ostream& os, const Container<T...>& con ){\
    os << "[";                                                 \
    std::string sep = "";                                      \
    for( const auto& y: con ){                                 \
        os << sep << y;                                        \
        sep = ",";                                             \
    }                                                          \
    return os << "]";                                          \
}
