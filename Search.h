// +--+--+--+--+--+-- ... --+ FF FF FF FF FF FF FF FF
// | d e  p  t  h |         |
// +--+--+--+--+--+-- ... --+    
struct TTEntry {
    static const u64 NODES_MASK = 0x07'FF'FF'FF'FF'FF'FF'FFULL;
    static const int DEPTH_SHFT = 59;
    
    u64 key;
    u64 data;
    
    u64 nodes() const {
        return data & NODES_MASK;
    }
    u8 depth() const {
        return data >> DEPTH_SHFT;
    }
    void save( u64 key, u64 nodes, u8 depth ){
        this->key = key;
        data = ((u64) depth << DEPTH_SHFT) | nodes;
    }
};
////////////////////////////////////////////////////////////////
class TranspositionTable {
private:
    vector <TTEntry> table;
    u64 mask;
public:
    TranspositionTable( u64 MB );
    void store( u64 key, u64 nodes, u8 depth );
    u64 probe( u64 key, u8 depth );
};
