void Bitboard::initialize() {
    const auto r8 = Board::PROMOTION_RANK[ WHITE ];
    const auto r1 = Board::PROMOTION_RANK[ BLACK ];
    const auto fa = Board::ROOK_FILE[ QUEENSIDE ];
    const auto fh = Board::ROOK_FILE[  KINGSIDE ];
    u8 bit = S - 1;
    for( int r = r8; r <= r1; ++r ){
        for( int f = fa; f <= fh; ++f ){
            const auto p = Board::get_pos( r, f );
            MAILBOX_TO_64[p] = bit;
            BITMASK[p] = 1ULL << bit;
            --bit;
        }
    }
    for( int r = r8; r <= r1; ++r ){
        for( int f = fa; f <= fh; ++f ){
            const auto p = Board::get_pos( r, f );
            for( int g = f + 2; g <= fh; ++g ){
                const auto q = Board::get_pos( r, g );
                ROOK_MASKS[p][q] = 
                ROOK_MASKS[q][p] =
                hrz_mask( MAILBOX_TO_64[p], MAILBOX_TO_64[q] );
            }
        }
    }
    for( int f = fa; f <= fh; ++f ){
        for( int r = r8; r <= r1; ++r ){
            const auto p = Board::get_pos( r, f );
            for( int s = r + 2; s <= r1; ++s ){
                const auto q = Board::get_pos( s, f );
                ROOK_MASKS[p][q] = 
                ROOK_MASKS[q][p] =
                vrt_mask( MAILBOX_TO_64[p], MAILBOX_TO_64[q] );
            }
        }
    }
}
////////////////////////////////////////////////////////////////
u64 Bitboard::hrz_mask( off_t a, off_t b ){
    u64 mask = 0;
    u64 bitmask = 1ULL <<-- a;
    for( off_t j = a; j > b; --j ){
        mask |= bitmask;
        bitmask >>= 1;
    }
    return mask;
}
////////////////////////////////////////////////////////////////
u64 Bitboard::vrt_mask( off_t a, off_t b ){
    u64 mask = 0;
    a -= W;
    u64 bitmask = 1ULL << a;
    for( off_t j = a; j > b; j -= W ){
        mask |= bitmask;
        bitmask >>= W;
    }
    return mask;
}
