std::ostream& operator<<( std::ostream& os, const dll& list ){
    os << '{';
    if( !list.empty()){
        off_t off = list.front();
        while( true ){
            os << off;
            off = list.next( off );
            if( !off ){ break; }
            os << ',';
        }
    }
    return os << '}';
}
